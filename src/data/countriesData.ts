/**
 * Fast lookup map by ISO Alpha-2 code (uppercase)
 */
export const COUNTRIES_BY_CODE: Record<string, Country> = COUNTRIES.reduce((acc, country) => {
  acc[country.code.toUpperCase()] = country;
  return acc;
}, {} as Record<string, Country>);

/**
 * Normalizes text for accent-insensitive and case-insensitive search
 */
export function normalizeSearchText(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}

/**
 * Look up country by ISO code or country name with fuzzy normalization
 */
export function findCountry(query?: string | null): Country | undefined {
  if (!query) return undefined;
  const trimmed = query.trim();
  const upper = trimmed.toUpperCase();

  // 1. Direct code lookup
  if (COUNTRIES_BY_CODE[upper]) {
    return COUNTRIES_BY_CODE[upper];
  }

  // 2. Normalized name or alias lookup
  const normalized = normalizeSearchText(trimmed);
  return COUNTRIES.find((c) => {
    if (normalizeSearchText(c.name) === normalized) return true;
    if (c.code.toLowerCase() === normalized) return true;
    return c.aliases.some((a) => normalizeSearchText(a) === normalized);
  });
}

/**
 * Get friendly country display name from code or name string
 */
export function getCountryName(value?: string | null, fallback = "International"): string {
  if (!value) return fallback;
  const found = findCountry(value);
  return found ? found.name : value;
}

/**
 * Get country flag emoji from code or name string
 */
export function getCountryFlag(value?: string | null): string {
  if (!value) return "🌐";
  const found = findCountry(value);
  return found ? found.flag : "🌐";
}

/**
 * Get country dial code from code or name string
 */
export function getCountryDialCode(value?: string | null): string {
  if (!value) return "+1";
  const found = findCountry(value);
  return found ? found.dialCode : "+1";
}
